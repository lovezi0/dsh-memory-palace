// memory-palace 共享常量：场景关键词 + 两个 LLM prompt（智能模式摘要 / 项目记忆蒸馏）。
// 纯常量模块，无状态、可被任意模块与单测直接引用。

// 场景关键词（增强原方案 D）：命中即视为"用户告知偏好 / 做出技术决策"，纯文本轮次也写。
export const SCENE_KEYWORDS = ["记住", "记一下", "remind", "偏好", "决定", "以后都", "约定", "采用", "根因", "修复"];

// 智能模式（memoryMode==="smart"）的摘要提炼 prompt（v1.4.0 起为函数，支持回喂存量记忆）。
// 让 LLM 输出 {summary, durable:[{scope,fact}], memoryOps:[...]}；memoryOps 用于基于编号的现有记忆做增量维护。
// allowDelete=true（手动蒸馏按钮）：开放 add/replace/delete；false（自动智能模式）：禁 delete，仅 add/replace。
// 注意：回喂是否实际发生由 distill.mjs 按 cfg().feedbackEnabled 决定（智能模式级，自动/手动均生效）；
// 此处仅声明能力边界——allowDelete 决定 prompt 是否允许 delete 指令（自动模式禁 delete，手动按钮放开）。
export function SUMMARY_PROMPT({ allowDelete = false, outputBudget } = {}) {
  const feedbackInstr = allowDelete
    ? "【维护现有记忆】若对话中提供了「项目级记忆 / 用户级记忆（逐行编号）」，你可在输出 memoryOps 中对现有记忆做增量维护：\n" +
      '- add：新增一条事实（scope + fact），勿与现有重复；\n' +
      '- replace：line=现有行号，oldText=该行精确原文，newText=替换后全文（仅内容行，禁止改动 # / <!-- 结构行）；\n' +
      '- delete：line=现有行号，oldText=该行精确原文（仅内容行，禁止删除 # / <!-- 结构行）；\n' +
      "所有 replace/delete 必须带 oldText 精确匹配（匹配失败将被拒绝、不修改任何内容）。"
    : "【维护现有记忆】若对话中提供了「项目级记忆 / 用户级记忆（逐行编号）」，你可在输出 memoryOps 中对现有记忆做增量维护：\n" +
      '- add：新增一条事实（scope + fact），勿与现有重复；\n' +
      '- replace：line=现有行号，oldText=该行精确原文，newText=替换后全文（仅内容行）；\n' +
      "（当前为自动模式，禁止使用 delete，避免误删记忆；replace 必须带 oldText 精确匹配，匹配失败将被拒绝。）";

  return (
    "你是会话记忆提炼助手。根据下面这段【新产生的】对话（含工具调用与结果），提炼两样东西：\n" +
    "1) summary：一段简洁中文摘要——这段对话做了什么、关键结果（路径/命令/数字）。\n" +
    "2) durable：值得跨 session 长期记住的事实列表（最多 3 条），每条带 scope：\n" +
    '   - "project" = 当前项目的约定/决策/技术事实\n' +
    '   - "user" = 跨项目的个人偏好/习惯\n' +
    "   闲聊、一次性操作、显而易见的内容、纯错误现象（错误已有独立记录）不要提炼；没有就留空数组。\n" +
    "【输出风格硬约束】\n" +
    "1) summary 必须是**客观、第三人称、陈述性**的中文摘要，描述「对话完成了什么 / 得出了什么结论」；\n" +
    "   **严禁**包含：提问、提议、请示、寒暄、自我指涉（如「我可以帮你…」「需要的话…」「要不要…」）、\n" +
    "   内心独白（如「But wait」「I should…」）或任何对话体 / 元叙述——你是在**写记忆**，不是在**对话**。\n" +
    "2) durable 每条必须是**可独立成立的客观事实**；**严禁**把「助手说过的话 / 向用户提问 / 未确认的提议」本身当作事实记录。\n" +
    "3) 若对话中仅含未决的提问或提议、无确定结论，summary 写「本次对话为未决讨论，暂无确定结论」，durable 留空，绝不可照抄对话体文本。\n" +
    feedbackInstr +
    (outputBudget != null ? "\n【输出长度约束】你的最终 JSON（summary + durable + memoryOps 合计）请控制在约 " + outputBudget + " token（≈" + Math.round(outputBudget * 1.8) + " 字）以内。思考/推理过程不受此限、可充分判断（含「该不该记」「是否一次性操作」「与旧记忆是否冲突需 update/delete」），但**最终成稿必须精炼、不超预算**；严禁为凑结构而填充无用内容。\n" : "") +
    "\n只输出 JSON，不要多余文字，格式：\n" +
    '{"summary":"...","durable":[{"scope":"project","fact":"一句话"}],"memoryOps":[{"op":"add","scope":"project","fact":"..."},{"op":"replace","line":12,"oldText":"...","newText":"..."},{"op":"delete","line":7,"oldText":"..."}]}\n' +
    "（没有需要维护的现有记忆时，memoryOps 留空数组 []。）"
  );
}

// 项目记忆蒸馏 prompt（供按钮「蒸馏项目记忆」稳定调用）。
// 用法：system = 本 prompt，user = 项目 MEMORY.md 全文，输出 = 精炼后的项目记忆（直接覆盖写回）。
export function DISTILL_PROMPT({ outputBudget } = {}) {
  return (
    "你是一名「项目记忆蒸馏器」。我会给你一份项目的原始材料（可能是记忆文件、会话记录、零散笔记，或多份材料的拼合）。你的任务：把它提炼成一段精炼的项目记忆。\n" +
  "\n" +
  "【提炼总原则】\n" +
  "只保留「以后还会用到」的信息，删掉「一次性过程」。\n" +
  "唯一判断标准：删了这条，下次开工会不会出错 / 返工 / 重踩坑？会 → 留；不会 → 删。\n" +
  "\n" +
  "【只提炼「以后还会用到」的信息，无关的类别直接省略，不要硬凑】\n" +
  "常见归档维度（参考，可按材料实际内容增删维度）：\n" +
  "1. 定位 —— 一句话说清任务本质 + 最终产出什么。\n" +
  "2. 当前状态 —— 现在推进到哪一步、卡在哪、下一步是什么。\n" +
  "3. 核心约束 —— 什么绝对不能变。注意：丢了会出事的才叫约束，丢了只是不方便的是细节，细节不写。\n" +
  "4. AI 行为边界 —— AI 能做什么、绝不能做什么、什么留给用户。若设置该章节，则所有「谁来做 / 谁授权 / 谁拍板」的约定集中于此。\n" +
  "5. 关键路径 —— 绝对路径、命令、数据源、模板、依赖。原样精确保留，禁止用占位符。\n" +
  "6. 决策记录 —— 为什么这么做（而非只记做了什么），尽量带日期或版本锚点。废弃方案单独标注为「已废弃」，不要删除。\n" +
  "7. 坑与教训 —— 现象 → 根因 → 解法，一条一个坑。一句话能讲清的坑不算坑、不记。\n" +
  "\n" +
  "【写法规则】\n" +
  "- 结论先行：一条 = 结论 + 关键参数，不写推导过程。\n" +
  "- 强动词：约束/边界用「必须 / 绝不 / 勿 / 除非…明确同意」这类词，不留模糊空间。\n" +
  "- 精确值：路径、命令、字段名、版本号原样保留，禁用 ~/、占位符或「大概」。\n" +
  "- 时间锚点：决策和坑尽量带日期或版本，让人知道这是哪个阶段的结论。\n" +
  "\n" +
  // v1.4.1：骨架从强制改为参考——章节可按内容增删/合并/改名，以契合为先（修实测的
  // 「章节与内容不匹配」）。下方自检第 6 条同步翻转为「查错位」，防收尾自检把自由度撤销。
  "【输出格式】参考以下骨架组织输出，章节可按材料实际内容增删/合并/改名，以内容与章节契合为先，无关章节不硬凑：\n" +
  "\n" +
  "# <项目名> 项目笔记\n" +
  "<一句话定位 + 当前状态>\n" +
  "\n" +
  "## 核心约束\n" +
  "- ...\n" +
  "\n" +
  "## AI 行为边界\n" +
  "- ...\n" +
  "\n" +
  "## 关键路径\n" +
  "- ...\n" +
  "\n" +
  "## 决策记录\n" +
  "- ...\n" +
  "\n" +
  "## 坑与教训\n" +
  "- ...\n" +
  "\n" +
  "【输出前自检，逐条过一遍】\n" +
  "1. 有没有混入一次性过程 / 临时路径 / 某次报错全文？\n" +
  "2. 每条「约束」删了会不会出事？\n" +
  "3. 边界是否显式、无歧义、没有混在别的条目里？\n" +
  "4. 路径 / 命令 / 版本号是否精确？\n" +
  "5. 每个坑是否「现象 → 根因 → 解法」三要素齐全？\n" +
  "6. 每个条目是否归在了最契合的章节？有没有为凑骨架而错位归类？\n" +
  "\n" +
  (outputBudget != null ? "【输出长度约束】你提炼后的项目记忆请控制在约 " + outputBudget + " token（≈" + Math.round(outputBudget * 1.8) + " 字）以内。思考不受限，但成稿须精炼、不超预算；只保留「以后还会用到」的信息，删掉「一次性过程」。\n" : "") +
  "现在开始处理我提供的材料。"
  );
}
